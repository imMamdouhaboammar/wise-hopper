تعالى ناخد مثال صغير من نفس الحملة:
لو الإعلان بتاعنا بيقول للمستخدم «حمّل Metadoc دلوقتي»، وبعد ما يضغط يكتشف إن عليه يسجل حساب، ويدور على طبيب، ويشوف المواعيد، ويمكن يدفع قبل ما يحجز، فكل خطوة من دول فيها معلومات واعتراضات وقرارات ممكن تأثر على استمراره.

