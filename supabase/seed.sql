هنا هتحتاجوا تتفقوا على حاجتين:

1. الهدف التجاري اللي هنراجع عليه نتيجة الحملة.

2. والـ Conversion Action اللي هنستخدمها في إدارة الإعلانات.

في المثال بتاعنا، الهدف التجاري هو أول استشارة مكتملة من مستخدم جديد. لكن لو التطبيق جديد ولسه حجم الاستشارات قليل، ممكن فريق الـ Performance يقترح استخدام حدث أقرب زي الحجز المؤكد أثناء مرحلة معينة من التعلم، لأن بياناته متاحة بحجم أكبر. وده قرار يتاخد بناءً على جودة الـ Tracking وحجم الأحداث وطريقة عمل المنصة، مع استمرار متابعة الاستشارات المكتملة باعتبارها النتيجة اللي إحنا عايزين نوصلها.

ولو شغال على Google Ads مثلًا، هتلاقي عندك Primary وSecondary Conversion Actions:

* **الـ Primary:** بتُستخدم في الـ Bidding لما تكون ضمن هدف الحملة المختار.

* **الـ Secondary:** بتكون للمراقبة في الإعدادات المعتادة، وفيه تفاصيل إضافية لو بتستخدم Custom Goals.

تقدر ترجع لـ شرح Google Ads الرسمي لو هتطبق النقطة دي على حملاتك.

بس خد بالك من اختيار الـ Event اللي المنصة هتتعلم عليه، لأن لو كل الـ Optimization بتاعتك ماشية ناحية الـ Downloads، ممكن تفضل تجيب مستخدمين بيحمّلوا التطبيق من غير ما تعرف إذا كانوا بيوصلوا للحجز أو الاستخدام الفعلي.

والموضوع بيكبر لما يبقى عندك Ads على أكتر من Channel، وكل Platform بتقيس وبتنسب الـ Conversions لنفسها بطريقة مختلفة. فخلّي تعريف الحدث ثابت قدر الإمكان، وراجع مع فريق الـ Analytics إزاي هتربط بيانات الإعلان ببيانات التطبيق، وإيه اللي تقدر تقيسه فعلًا، وإيه اللي محتاج يفضل مجرد تقدير.

