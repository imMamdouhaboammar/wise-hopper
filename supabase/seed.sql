<h2>طيب، إحنا فين من كل ده؟</h2>
<div class="editorial-callout editorial-callout-info" data-type="info"><span class="editorial-callout-title">المبدأ الجوهري في Conversion Copywriting</span><div class="editorial-callout-body">دي أول حاجة عايزك تفهمها وإنت بتبدأ تتعلم Conversion Copywriting، لأن جزء كبير من شغلك هيبقى إنك تفهم الـ Business كويس كفاية عشان تعرف الناس المفروض تعمل إيه بعد ما تشوف الكلام اللي إنت كتبته، وإزاي هنقيس إذا كانت عملته فعلًا.</div></div>
<p>وخلينا نمسك مثال واحد نفضل نشتغل عليه خلال السلسلة دي، عشان كل حاجة نتعلمها تتحول قدامك لقرار تقدر تطبقه على Campaign عندك، ونوصل في الآخر لحملة كاملة عندها Messages وCopies وCreative Direction وطريقة واضحة لقياس الأداء.</p>
<p>هنستخدم مثال <strong>Metadoc</strong> الموجود في الكورس، وهو تطبيق بيقدم خدمات رعاية صحية، منها الـ Tele-Consultation اللي بتسمح للمستخدم يتواصل مع طبيب عن بُعد.</p>
<p>الـ Brief التعليمي عندنا فيه هدفين:</p>
<ol>
<li>الأول إننا نعرّف المستخدمين الحاليين بالخدمة ونشجعهم يجربوها.</li>
<li>والتاني إننا نجيب مستخدمين جدد للتطبيق وللخدمة نفسها.</li>
</ol>
<p>وخلينا نختار الهدف التاني دلوقتي، عشان ندخل في حتة الـ Acquisition ونشوف إزاي هنكتسب مستخدمين جدد، ونساعدهم يوصلوا لأول استخدام فعلي للخدمة Conversion Copywriting Crash Course V 2.0.docx.</p>
<h2>أول سؤال في الـ Brief المفروض يكون إيه؟ <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="lucide lucide-circle-question-mark lucide-help-circle lucide-circle-help editorial-icon inline-block align-middle" aria-hidden="true"><circle cx="12" cy="12" r="10"></circle><path d="M9.09 9a3 3 0 0 1 5.83 1c0 2-3 3-3 3"></path><path d="M12 17h.01"></path></svg></h2>
<p>أنا عايزك تتخيل إنك قاعد قدام صاحب الـ Business، وهو بيقولك عايز أكبر عدد ممكن من الـ Downloads.</p>
<p>هنا عندك فرصة تسأله سؤال صغير قبل ما تبدأ تكتب:</p>
<blockquote class="editorial-pullquote"><p>«إحنا عايزين الناس تحمّل التطبيق عشان يحصل إيه بعدها؟»</p>— السؤال الأهم قبل كتابة أول Headline</blockquote>
<p>ممكن يقولك إن التطبيق لسه جديد، وإحنا حاليًا بنحاول نكبر قاعدة المستخدمين، وممكن يقولك إنه عنده مستخدمين كتير بس الناس مش بتستخدم الخدمة الجديدة، وممكن يكون عنده هدف مالي واضح محتاج يحققه من الاستشارات خلال فترة معينة.</p>
<p>كل إجابة من دول هتأثر على الحملة اللي هتبنيها:</p>
<ul>
<li>لو هدفه فعلًا زيادة الـ Installs في المرحلة الحالية، محتاج تعرف ليه الرقم ده مهم للبيزنس، وإزاي هيتحول بعد كده لقيمة، وإيه تكلفة اكتساب المستخدم اللي يقدر يتحملها.</li>
<li>ولو هدفه إن مستخدمين جدد يجربوا الخدمة، يبقى لازم تتفقوا على معنى كلمة «يجربوا»: هل التجربة بتحصل بمجرد إنشاء حساب؟ ولا بعد حجز موعد؟ ولا لما المستخدم يكمل أول استشارة ليه فعلًا؟</li>
</ul>
<p>خلينا نفترض إننا اتفقنا في المثال التعليمي بتاعنا على إن النجاح معناه <strong>مستخدم جديد أكمل أول استشارة من خلال التطبيق</strong>. كده إحنا عندنا Business Objective واضح، ونقدر نبدأ نحوله لحاجة قابلة للقياس.</p>
<p>بس خد بالك، أنا هنا لسه عامل افتراض تعليمي، لأن أي Campaign فعلية محتاجة تتأكد من الهدف ده مع صاحب المشروع، وتعرف هل عنده القدرة إنه يقيس الاستشارات المكتملة، وهل هو مستعد يستثمر في اكتساب المستخدم لحد المرحلة دي.</p>
<p>وعلى فكرة، أول ما تبدأ تسأل الأسئلة دي هتكتشف إن الـ Brief نفسه محتاج شوية شغل: فيه معلومات عن المنتج، ومعلومات عن الجمهور، ومعلومات عن الـ Pricing والـ Offer، وفيه حاجات المفروض تكون جاية من الـ Analytics أو من التيم اللي بيقدم الخدمة، وكل واحدة منهم هتدخل معاك بعد كده في القرارات اللي هتاخدها.</p>
<h2>تعالى نحدد الـ Conversion Event <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="lucide lucide-target editorial-icon inline-block align-middle" aria-hidden="true"><circle cx="12" cy="12" r="10"></circle><circle cx="12" cy="12" r="6"></circle><circle cx="12" cy="12" r="2"></circle></svg></h2>
<p>الـ Conversion ببساطة هي الحركة اللي إحنا عايزين المستخدم يعملها، وبنقدر نسجل إنها حصلت. ممكن تكون Purchase أو Sign-up أو Lead Form Submission أو Booking أو App Install، حسب طبيعة المنتج والهدف اللي شغالين عليه.</p>
<p>لكن في Metadoc إحنا اتفقنا إن الـ Business عايز مستخدمين جدد يوصلوا لأول استشارة فعلية، فخلينا نختار <strong>أول استشارة مكتملة من مستخدم جديد</strong> باعتبارها الـ Primary Business Conversion Event في المثال بتاعنا.</p>
<p>والاختيار ده محتاج تعريف أدق شوية عشان الناس اللي هتشتغل على الـ Tracking تبقى فاهمة إحنا بنقيس إيه:</p>
<ul>
<li>يعني إيه مستخدم جديد؟ هل هو اللي أول مرة يعمل Account؟ ولا اللي عمره ما استخدم خدمة الـ Tele-Consultation حتى لو عنده حساب قديم؟</li>
<li>وإمتى هنعتبر الاستشارة مكتملة؟ بمجرد ما المكالمة تبدأ؟ ولا لما تنتهي ويتم تسجيل حالتها على إنها Completed؟</li>
</ul>
<p>بما إننا اخترنا الـ Acquisition، هنعتبر في التمرين بتاعنا إن المستخدم الجديد هو شخص أنشأ حسابه لأول مرة خلال فترة الحملة، والاستشارة المكتملة هي اللي التطبيق سجل إنها انتهت بنجاح، وهنحسب أول استشارة مكتملة لكل مستخدم مرة واحدة. كده لو الشخص نفسه حجز 3 استشارات، مش هنحسبه 3 مستخدمين جدد في الـ Acquisition Report.</p>
<p>طبعًا تعريف الحدث ونافذة القياس وطريقة ربط المستخدمين بالأحداث لازم تتراجع مع فريق الـ Product والـ Analytics قبل إطلاق أي Campaign فعلية.</p>
<p>طيب، بما إننا عايزين أول استشارة مكتملة، هل كده هنتجاهل الـ Downloads والـ Sign-ups والحجوزات؟
طبعًا لأ، لأننا محتاجين نعرف المستخدم بيعمل إيه في كل مرحلة، وإيه اللي بيحصل بين أول مرة يشوف فيها الإعلان ولحد ما يستخدم الخدمة.</p>
