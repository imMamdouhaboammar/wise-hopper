* ولو المستخدم واجه مشكلة أثناء الحجز، إيه اللي بيحصل؟

أنا هنا عايزك تروح لصاحب الـ Product أو الـ Account Manager وتسأله عن الحاجات دي، لأن أي Feature هتستخدمها في الكوبي لازم تكون موجودة فعلًا، وأي Offer هتعلن عنها لازم تكون متأكد من شروطها. ممكن جدًا أول إجابة تسمعها تكون: «استنى نسأل التيم ونرجعلك»، عادي، المهم إنك تعرف إيه المعلومات المؤكدة وإيه اللي لسه محتاج مراجعة قبل ما تتحول لوعد موجود في الإعلان.

## إطار TTPM قبل اعتماد أي Message

وفيه حاجة اسمها **TTPM** عايزك تحطها جنب الـ Brief. قبل ما تعتمد أي Message، محتاج تشوف أربع حاجات بتأثر على طريقة تقديمها، وهي: Timing وTargeting وPlacement وMessaging. هنرجع نتعمق فيها مع بعض، بس خليني أوريك إزاي تستخدمها دلوقتي على مثال Metadoc:

| الركن | الرمز | التطبيق على حملة Metadoc |
| :--- | :--- | :--- |
| **التوقيت** <Icon name="Clock" /> | Timing | مرتبط باللحظة اللي الشخص ممكن يحتاج فيها الخدمة، وبالمواعيد الفعلية المتاحة للحجز، وبإمكانية الفريق إنه يستقبل الطلبات اللي الحملة هتجيبها. |
| **الاستهداف** <Icon name="Users" /> | Targeting | لازم يخلينا نعرف إحنا بنحاول نجيب مستخدمين جدد ولا بنخاطب ناس عندها حساب بالفعل، لأن كل مجموعة عندها معرفة مختلفة بالتطبيق. |
| **المكان والمنصة** <Icon name="Compass" /> | Placement | هنختاره بناءً على الأماكن اللي الجمهور المستهدف موجود فيها وطبيعة المحتوى اللي بيستهلكه، مع متابعة الأداء الفعلي لكل Channel. |
| **الرسالة الإعلانية** <Icon name="FileText" /> | Messaging | دي شغلانتنا اللي هنقعد نتعمق فيها خلال الحلقات الجاية، وهنشوف إزاي نستخدم الـ Customer Research عشان نفهم إيه اللي بيشغل بال الشخص قبل الحجز. |

خليك فاكر إننا لسه في مرحلة إعداد الحملة، فكل قرار هنا قابل للمراجعة لما تبدأ تظهر لنا معلومات فعلية عن الجمهور والمنتج والأداء.

## طيب، افتح الـ Brief بتاعك وتعالى نشتغل <Icon name="FileText" />

