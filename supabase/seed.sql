## تعالى نحدد الـ Conversion Event <Icon name="Target" />

الـ Conversion ببساطة هي الحركة اللي إحنا عايزين المستخدم يعملها، وبنقدر نسجل إنها حصلت. ممكن تكون Purchase أو Sign-up أو Lead Form Submission أو Booking أو App Install، حسب طبيعة المنتج والهدف اللي شغالين عليه.

لكن في Metadoc إحنا اتفقنا إن الـ Business عايز مستخدمين جدد يوصلوا لأول استشارة فعلية، فخلينا نختار **أول استشارة مكتملة من مستخدم جديد** باعتبارها الـ Primary Business Conversion Event في المثال بتاعنا.

والاختيار ده محتاج تعريف أدق شوية عشان الناس اللي هتشتغل على الـ Tracking تبقى فاهمة إحنا بنقيس إيه:
* يعني إيه مستخدم جديد؟ هل هو اللي أول مرة يعمل Account؟ ولا اللي عمره ما استخدم خدمة الـ Tele-Consultation حتى لو عنده حساب قديم؟
* وإمتى هنعتبر الاستشارة مكتملة؟ بمجرد ما المكالمة تبدأ؟ ولا لما تنتهي ويتم تسجيل حالتها على إنها Completed؟

بما إننا اخترنا الـ Acquisition، هنعتبر في التمرين بتاعنا إن المستخدم الجديد هو شخص أنشأ حسابه لأول مرة خلال فترة الحملة، والاستشارة المكتملة هي اللي التطبيق سجل إنها انتهت بنجاح، وهنحسب أول استشارة مكتملة لكل مستخدم مرة واحدة. كده لو الشخص نفسه حجز 3 استشارات، مش هنحسبه 3 مستخدمين جدد في الـ Acquisition Report.

طبعًا تعريف الحدث ونافذة القياس وطريقة ربط المستخدمين بالأحداث لازم تتراجع مع فريق الـ Product والـ Analytics قبل إطلاق أي Campaign فعلية.

طيب، بما إننا عايزين أول استشارة مكتملة، هل كده هنتجاهل الـ Downloads والـ Sign-ups والحجوزات؟
طبعًا لأ، لأننا محتاجين نعرف المستخدم بيعمل إيه في كل مرحلة، وإيه اللي بيحصل بين أول مرة يشوف فيها الإعلان ولحد ما يستخدم الخدمة.

ودي الحتة اللي هندخل فيها على الـ Conversion Funnel.

