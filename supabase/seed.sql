فتبدأ تعمل اللي اتعلمته من الكورسات، تفتح Google، تشوف المنافسين، تدخل على Meta Ads Library، تجمع شوية References، وتفتح ملف جديد تكتب فيه الـ Headlines والـ Hooks والـ Copies اللي هتشتغل عليها.

ممكن فعلًا تطلع حملة شكلها حلو جدًا، والـ Creative Team تتبسط بيها، والكلاينت يوافق من أول Presentation، وتنزل الإعلانات وتبدأ تجيب Engagement وClicks وDownloads، وبعدها تكتشف إن الناس اللي دخلت التطبيق مستخدمتش الخدمة اللي المفروض الحملة اتعملت عشانها.

وساعتها غالبًا هيبدأ النقاش المعتاد:
* [icon:Sparkles] **الـ Copywriter** شايف إن الكوبيز عملت شغلها وجابت Clicks.
* [icon:TrendingUp] **الـ Media Buyer** شايف إن الـ Cost per Install كويسة.
* [icon:Users] **الـ Account Manager** بيحاول يفهم ليه الكلاينت مش مبسوط رغم إن الأرقام اللي في الـ Report كلها تقريبًا خضرا.

وكل واحد عنده وجهة نظر ممكن تكون صحيحة فعلًا، حسب هو بيبص على أنهي رقم.

## طيب، إحنا فين من كل ده؟

> [!info] المبدأ الجوهري في Conversion Copywriting
> دي أول حاجة عايزك تفهمها وإنت بتبدأ تتعلم Conversion Copywriting، لأن جزء كبير من شغلك هيبقى إنك تفهم الـ Business كويس كفاية عشان تعرف الناس المفروض تعمل إيه بعد ما تشوف الكلام اللي إنت كتبته، وإزاي هنقيس إذا كانت عملته فعلًا.

وخلينا نمسك مثال واحد نفضل نشتغل عليه خلال السلسلة دي، عشان كل حاجة نتعلمها تتحول قدامك لقرار تقدر تطبقه على Campaign عندك، ونوصل في الآخر لحملة كاملة عندها Messages وCopies وCreative Direction وطريقة واضحة لقياس الأداء.

هنستخدم مثال **Metadoc** الموجود في الكورس، وهو تطبيق بيقدم خدمات رعاية صحية، منها الـ Tele-Consultation اللي بتسمح للمستخدم يتواصل مع طبيب عن بُعد.

الـ Brief التعليمي عندنا فيه هدفين:
1. الأول إننا نعرّف المستخدمين الحاليين بالخدمة ونشجعهم يجربوها.
2. والتاني إننا نجيب مستخدمين جدد للتطبيق وللخدمة نفسها.

وخلينا نختار الهدف التاني دلوقتي، عشان ندخل في حتة الـ Acquisition ونشوف إزاي هنكتسب مستخدمين جدد، ونساعدهم يوصلوا لأول استخدام فعلي للخدمة Conversion Copywriting Crash Course V 2.0.docx.

## أول سؤال في الـ Brief المفروض يكون إيه؟ [icon:HelpCircle]

أنا عايزك تتخيل إنك قاعد قدام صاحب الـ Business، وهو بيقولك عايز أكبر عدد ممكن من الـ Downloads.

هنا عندك فرصة تسأله سؤال صغير قبل ما تبدأ تكتب:

> "إحنا عايزين الناس تحمّل التطبيق عشان يحصل إيه بعدها؟" — السؤال الأهم قبل كتابة أول Headline

ممكن يقولك إن التطبيق لسه جديد، وإحنا حاليًا بنحاول نكبر قاعدة المستخدمين، وممكن يقولك إنه عنده مستخدمين كتير بس الناس مش بتستخدم الخدمة الجديدة، وممكن يكون عنده هدف مالي واضح محتاج يحققه من الاستشارات خلال فترة معينة.

كل إجابة من دول هتأثر على الحملة اللي هتبنيها:
* لو هدفه فعلًا زيادة الـ Installs في المرحلة الحالية، محتاج تعرف ليه الرقم ده مهم للبيزنس، وإزاي هيتحول بعد كده لقيمة، وإيه تكلفة اكتساب المستخدم اللي يقدر يتحملها.
* ولو هدفه إن مستخدمين جدد يجربوا الخدمة، يبقى لازم تتفقوا على معنى كلمة «يجربوا»: هل التجربة بتحصل بمجرد إنشاء حساب؟ ولا بعد حجز موعد؟ ولا لما المستخدم يكمل أول استشارة ليه فعلًا؟

خلينا نفترض إننا اتفقنا في المثال التعليمي بتاعنا على إن النجاح معناه **مستخدم جديد أكمل أول استشارة من خلال التطبيق**. كده إحنا عندنا Business Objective واضح، ونقدر نبدأ نحوله لحاجة قابلة للقياس.

بس خد بالك، أنا هنا لسه عامل افتراض تعليمي، لأن أي Campaign فعلية محتاجة تتأكد من الهدف ده مع صاحب المشروع، وتعرف هل عنده القدرة إنه يقيس الاستشارات المكتملة، وهل هو مستعد يستثمر في اكتساب المستخدم لحد المرحلة دي.

وعلى فكرة، أول ما تبدأ تسأل الأسئلة دي هتكتشف إن الـ Brief نفسه محتاج شوية شغل: فيه معلومات عن المنتج، ومعلومات عن الجمهور، ومعلومات عن الـ Pricing والـ Offer، وفيه حاجات المفروض تكون جاية من الـ Analytics أو من التيم اللي بيقدم الخدمة، وكل واحدة منهم هتدخل معاك بعد كده في القرارات اللي هتاخدها.

## تعالى نحدد الـ Conversion Event [icon:Target]

الـ Conversion ببساطة هي الحركة اللي إحنا عايزين المستخدم يعملها، وبنقدر نسجل إنها حصلت. ممكن تكون Purchase أو Sign-up أو Lead Form Submission أو Booking أو App Install، حسب طبيعة المنتج والهدف اللي شغالين عليه.

لكن في Metadoc إحنا اتفقنا إن الـ Business عايز مستخدمين جدد يوصلوا لأول استشارة فعلية، فخلينا نختار **أول استشارة مكتملة من مستخدم جديد** باعتبارها الـ Primary Business Conversion Event في المثال بتاعنا.

والاختيار ده محتاج تعريف أدق شوية عشان الناس اللي هتشتغل على الـ Tracking تبقى فاهمة إحنا بنقيس إيه:
* يعني إيه مستخدم جديد؟ هل هو اللي أول مرة يعمل Account؟ ولا اللي عمره ما استخدم خدمة الـ Tele-Consultation حتى لو عنده حساب قديم؟
* وإمتى هنعتبر الاستشارة مكتملة؟ بمجرد ما المكالمة تبدأ؟ ولا لما تنتهي ويتم تسجيل حالتها على إنها Completed؟

بما إننا اخترنا الـ Acquisition، هنعتبر في التمرين بتاعنا إن المستخدم الجديد هو شخص أنشأ حسابه لأول مرة خلال فترة الحملة، والاستشارة المكتملة هي اللي التطبيق سجل إنها انتهت بنجاح، وهنحسب أول استشارة مكتملة لكل مستخدم مرة واحدة. كده لو الشخص نفسه حجز 3 استشارات، مش هنحسبه 3 مستخدمين جدد في الـ Acquisition Report.

طبعًا تعريف الحدث ونافذة القياس وطريقة ربط المستخدمين بالأحداث لازم تتراجع مع فريق الـ Product والـ Analytics قبل إطلاق أي Campaign فعلية.

طيب، بما إننا عايزين أول استشارة مكتملة، هل كده هنتجاهل الـ Downloads والـ Sign-ups والحجوزات؟
طبعًا لأ، لأننا محتاجين نعرف المستخدم بيعمل إيه في كل مرحلة، وإيه اللي بيحصل بين أول مرة يشوف فيها الإعلان ولحد ما يستخدم الخدمة.

ودي الحتة اللي هندخل فيها على الـ Conversion Funnel.

## نرسم رحلة المستخدم على ورقة [icon:TrendingUp]

تخيل واحد شاف إعلان لـ Metadoc لأول مرة، دخل على صفحة التطبيق، حمّله، فتحه وسجل حساب، وبعدها بدأ يدور على موعد مناسب، واختار طبيب وحجز استشارته. لحد هنا عندك مجموعة Events تقدر تتابعها، ولو عرفت تربطهم ببعض هتبدأ تشوف الناس بتتوقف فين.

تعالى نفترض إن عندنا رحلة بالشكل ده (مثال رقمي افتراضي للتعليم فقط):

```mermaid
graph TD
  Visitors["Landing Page Visitors<br/><b>2,000</b> (100%)"] -->|30%| Installs["App Installs<br/><b>600</b> (30%)"]
  Installs -->|60%| Signups["Sign-ups<br/><b>360</b> (18%)"]
  Signups -->|30%| Bookings["Consultations Booked<br/><b>108</b> (5.4%)"]
  Bookings -->|66.7%| Completed["First Consultations Completed<br/><b>72</b> (3.6%)"]
```

### قمع التحويل للمستخدم الجديد (Metadoc | New-user conversion funnel)

| المرحلة في الرحلة | العدد | النسبة من الزوار | معدل الانتقال للخطوة التالية |
| :--- | :--- | :--- | :--- |
| **Landing Page Visitors** | 2,000 | 100% من زوار الـ Landing Page | — |
| **App Installs** | 600 | 30% من زوار الـ Landing Page | 30% من الزيارة للتحميل |
| **Sign-ups** | 360 | 18% من زوار الـ Landing Page | Install → Sign-up: 60% |
| **Consultations Booked** | 108 | 5.4% من زوار الـ Landing Page | Sign-up → Booking: 30% |
| **First Consultations Completed** | 72 | 3.6% من زوار الـ Landing Page | Booking → Completion: 66.7% |

* **معدل التحويل الكلي (Visitor → First consultation):** 3.6%

بص على الأرقام دي شوية، لأن دي اللحظة اللي الـ Copywriter بيبدأ يشوف فيها الـ Campaign من مكان مختلف. من أصل 2000 زائر، عندنا 600 عملوا Install، وده معناه إن معدل التحويل من الزيارة للتحميل في المثال ده 30%. حلو.

بعدها 360 شخص سجلوا حساب جديد، يعني 60% من اللي حمّلوا التطبيق كملوا الـ Sign-up. بعد ذلك 108 بس حجزوا استشارة، فإحنا كده عندنا 30% من المسجلين وصلوا للحجز، وفي الآخر 72 شخص أكملوا أول استشارة فعلًا. الـ Conversion Rate من أول زيارة لحد أول استشارة مكتملة هنا 3.6%.

طيب تخيل إنك قاعد بتراجع الحملة ولقيت الـ Installs ممتازة، والـ Sign-ups ماشية بشكل كويس، بس عندنا ناس كتير جدًا بتقف بعد التسجيل وقبل الحجز.

ممكن تروح تفكر في Copy جديدة، بس أنا عايزك هنا تفتح مساحة لأسئلة تانية قبل ما تقرر:
* هل الناس بعد ما بتسجل بتعرف تلاقي الخدمة بسهولة؟
* هل المواعيد المناسبة متاحة؟
* هل السعر واضح قبل الحجز؟
* هل فيه حاجة في الـ Booking Flow بتطلب منهم معلومات كتير؟
* هل الإعلان خلق توقع معين، ولما الناس دخلت التطبيق لقت تجربة مختلفة؟

وممكن جدًا تكون المشكلة مرتبطة بالـ Messaging، أو بالـ Offer، أو بالـ UX، أو بتوفر المواعيد، أو بكذا حاجة مع بعض. فإنك تعرف إن الناس وقفت عند خطوة معينة بيساعدك تحدد فين تبدأ البحث، وبعد كده تحتاج تفهم ليه وقفت هناك.

ودي من الحاجات المهمة اللي هتفيدك لما تبدأ تعمل Conversion Research وتراجع تسجيلات الجلسات، وأسئلة الـ Customer Support، والـ Interviews، والـ Analytics، بدل ما تفضل كل مرة تغير الـ Headline وتقول نجرب يمكن ربنا يكرم 😄.

## حلو، دلوقتي نحسب تكلفة القرار اللي إحنا عايزينه [icon:DollarSign]

تعالى نضيف رقم جديد للمثال الافتراضي: افترض إن الـ Media Spend بتاعتنا كانت 72 ألف جنيه، والـ Campaign جابت الـ 600 Downloads والـ 72 استشارة مكتملة اللي اتكلمنا عنهم:
* لو حسبت **تكلفة الـ Install**، هتلاقي إننا دفعنا 120 جنيه تقريبًا لكل تحميل.
* لكن لما تحسب **تكلفة أول استشارة مكتملة**، هتلاقي إننا دفعنا 1000 جنيه لكل مستخدم جديد أكمل استشارته الأولى.

شفت إزاي ممكن نفس الـ Campaign تطلعلك رقمين مختلفين تمامًا حسب إنت بتقيس إيه؟ والـ 1000 جنيه دول عبارة عن تكلفة الميديا لكل استشارة مكتملة في المثال، ولسه عندك تكاليف تانية لو هتحسب الـ CAC الكامل، زي تكاليف إنتاج الحملة وأي تكاليف اكتساب إضافية مرتبطة بيها.

طيب، هل 1000 جنيه رقم كويس؟
السؤال ده محتاج بيانات من الـ Business:
* الاستشارة الواحدة بتدخل للشركة كام؟
* تكاليف تقديم الخدمة قد إيه؟
* هل المستخدم الجديد متوقع يرجع يستخدم التطبيق تاني؟
* هل فيه خدمات تانية ممكن يشتريها؟
* وهل عندنا بيانات تسمح نقدر الـ Customer Lifetime Value بتاعته بشكل معقول؟

لو صاحب المشروع شايف إن تكلفة اكتساب المستخدم دي أعلى من القيمة الاقتصادية المتوقعة منه، يبقى عندنا مشكلة محتاجة نفهمها، حتى لو عدد الـ Downloads كبير والـ Dashboard شكلها يفتح النفس. وعشان كده أنا عايزك تتعود من البداية إنك تربط الـ Conversion Rate بهدف اقتصادي واضح.

> [!warning] تنبيه CXL حول رفع معدل التحويل
> CXL عندهم نقطة مهمة في [دليل الـ Conversion Rate Optimization](https://cxl.com/conversion-rate-optimization)، وهي إن رفع الـ Conversion Rate لوحده ممكن يوصلك لقرار تجاري سيئ لو عملته مثلًا عن طريق تخفيض السعر بشكل يضر ربحية البيزنس. والمثال ده مفيد جدًا للـ Copywriter، لأن ساعات بتبقى قادر تقدم Offer يجيب استجابة أعلى، بس محتاج تعرف أثره على الـ Margin وعلى نوعية العملاء اللي بيجوا من خلاله.

## طب والـ Media Buyer، هنقوله يقيس إيه؟ [icon:BarChart]

هنا هتحتاجوا تتفقوا على حاجتين:
1. الهدف التجاري اللي هنراجع عليه نتيجة الحملة.
2. والـ Conversion Action اللي هنستخدمها في إدارة الإعلانات.

في المثال بتاعنا، الهدف التجاري هو أول استشارة مكتملة من مستخدم جديد. لكن لو التطبيق جديد ولسه حجم الاستشارات قليل، ممكن فريق الـ Performance يقترح استخدام حدث أقرب زي الحجز المؤكد أثناء مرحلة معينة من التعلم، لأن بياناته متاحة بحجم أكبر. وده قرار يتاخد بناءً على جودة الـ Tracking وحجم الأحداث وطريقة عمل المنصة، مع استمرار متابعة الاستشارات المكتملة باعتبارها النتيجة اللي إحنا عايزين نوصلها.

ولو شغال على Google Ads مثلًا، هتلاقي عندك Primary وSecondary Conversion Actions:
* **الـ Primary:** بتُستخدم في الـ Bidding لما تكون ضمن هدف الحملة المختار.
* **الـ Secondary:** بتكون للمراقبة في الإعدادات المعتادة، وفيه تفاصيل إضافية لو بتستخدم Custom Goals.

تقدر ترجع لـ [شرح Google Ads الرسمي](https://support.google.com/google-ads/answer/11461796?hl=en) لو هتطبق النقطة دي على حملاتك.

بس خد بالك من اختيار الـ Event اللي المنصة هتتعلم عليه، لأن لو كل الـ Optimization بتاعتك ماشية ناحية الـ Downloads، ممكن تفضل تجيب مستخدمين بيحمّلوا التطبيق من غير ما تعرف إذا كانوا بيوصلوا للحجز أو الاستخدام الفعلي.

والموضوع بيكبر لما يبقى عندك Ads على أكتر من Channel، وكل Platform بتقيس وبتنسب الـ Conversions لنفسها بطريقة مختلفة. فخلّي تعريف الحدث ثابت قدر الإمكان، وراجع مع فريق الـ Analytics إزاي هتربط بيانات الإعلان ببيانات التطبيق، وإيه اللي تقدر تقيسه فعلًا، وإيه اللي محتاج يفضل مجرد تقدير.

## نرجع بقا للكلام اللي هنكتبه في الإعلان [icon:Sparkles]

بعد كل الحسابات دي، ممكن تسألني: يا عم هو أنا كـ Copywriter هقعد أعمل شغل الـ Performance Team كمان؟
لأ يا سيدي، إحنا عندنا ناس متخصصة في كل جزء، بس إنت محتاج تفهم الأرقام دي لأنها هتحدد إنت بتكتب لمين، وبتقوله إيه، وعايزه يعمل إيه بعد ما يقرأ.

تعالى ناخد مثال صغير من نفس الحملة:
لو الإعلان بتاعنا بيقول للمستخدم «حمّل Metadoc دلوقتي»، وبعد ما يضغط يكتشف إن عليه يسجل حساب، ويدور على طبيب، ويشوف المواعيد، ويمكن يدفع قبل ما يحجز، فكل خطوة من دول فيها معلومات واعتراضات وقرارات ممكن تأثر على استمراره.

في المقابل، لما تبقى فاهم رحلة المستخدم، تقدر تبني الرسالة اللي تشرح قيمة الخدمة، وتوضح الخطوة اللي جاية، وتجاوب عن السؤال المناسب في الوقت اللي الشخص محتاج فيه الإجابة.

بس عشان تكتب الكلام ده، محتاج تعرف تفاصيل المنتج نفسه:
* هل الاستشارة متاحة في كل الأوقات؟
* هل فيه تخصصات معينة؟
* إيه أسعار الاستشارات؟
* هل فيه Offer لأول استخدام؟
* هل المستخدم يقدر يشوف المواعيد قبل ما يسجل؟
* مين الأطباء الموجودين على التطبيق وإيه المعلومات الموثقة اللي نقدر نستخدمها عنهم؟
* ولو المستخدم واجه مشكلة أثناء الحجز، إيه اللي بيحصل؟

أنا هنا عايزك تروح لصاحب الـ Product أو الـ Account Manager وتسأله عن الحاجات دي، لأن أي Feature هتستخدمها في الكوبي لازم تكون موجودة فعلًا، وأي Offer هتعلن عنها لازم تكون متأكد من شروطها. ممكن جدًا أول إجابة تسمعها تكون: «استنى نسأل التيم ونرجعلك»، عادي، المهم إنك تعرف إيه المعلومات المؤكدة وإيه اللي لسه محتاج مراجعة قبل ما تتحول لوعد موجود في الإعلان.

